#!/usr/bin/env node
// discovery-to-roadmap.mjs — render discovery findings into ROADMAP candidates.
//
//   node scripts/discovery-to-roadmap.mjs --apply   # write the candidates section
//   node scripts/discovery-to-roadmap.mjs --check   # fail (exit 1) if ROADMAP drifts
//
// Reads .spec-graph/DISCOVERY.md (findings under "## Competitive Scan" and
// "## Voice of the Customer"), validates the intake format, and renders a
// "## Discovery Candidates" section in .spec-graph/ROADMAP.md. Only that
// generated section is touched; hand-written roadmap rows are never rewritten.
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const DISCOVERY = path.join(root, '.spec-graph', 'DISCOVERY.md');
const ROADMAP = path.join(root, '.spec-graph', 'ROADMAP.md');
const SECTION = '## Discovery Candidates';
const SOURCE_TYPES = ['internal-observation', 'public-docs', 'hypothesis', 'user-feedback', 'user-request'];
const IMPACTS = ['high', 'medium', 'low'];

function fail(msg) {
  console.error(`DISCOVERY-INVALID — ${msg}`);
  process.exit(1);
}

function parseDiscovery() {
  if (!fs.existsSync(DISCOVERY)) {
    console.log('DISCOVERY-ABSENT — no .spec-graph/DISCOVERY.md; nothing to render');
    return null;
  }
  const txt = fs.readFileSync(DISCOVERY, 'utf8');
  const findings = [];
  const blocks = txt.split(/^###\s+/m).slice(1);
  for (const block of blocks) {
    const idMatch = block.match(/^([DV]-\d{3})\s+—\s+(.+)$/m);
    if (!idMatch) continue;
    const id = idMatch[1];
    const title = idMatch[2].trim();
    const field = (name) => {
      const lines = block.split('\n');
      const re = new RegExp(`^- ${name}:\\s*(.*)$`);
      const idx = lines.findIndex(l => re.test(l));
      if (idx === -1) return null;
      const parts = [lines[idx].match(re)[1].trim()];
      for (let i = idx + 1; i < lines.length; i++) {
        if (/^\s{2,}\S/.test(lines[i])) { parts.push(lines[i].trim()); continue; }
        break;
      }
      return parts.join(' ').replace(/\s+/g, ' ').trim();
    };
    const sourceType = field('Source type');
    const date = field('Date');
    const impact = field('Impact');
    const proposed = field('Proposed');
    const observation = field('Observation') || field('Paraphrase');
    if (!SOURCE_TYPES.includes(sourceType)) fail(`${id}: invalid Source type "${sourceType}" (allowed: ${SOURCE_TYPES.join(', ')})`);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(date || '')) fail(`${id}: missing or invalid Date (YYYY-MM-DD)`);
    if (!IMPACTS.includes(impact)) fail(`${id}: invalid Impact "${impact}" (allowed: ${IMPACTS.join(', ')})`);
    if (!observation) fail(`${id}: missing Observation/Paraphrase line`);
    if (!proposed) fail(`${id}: missing Proposed line`);
    findings.push({ id, title, sourceType, date, impact, proposed });
  }
  if (!findings.length) fail('no findings parsed (expected "### D-001 — title" blocks)');
  const seen = new Set();
  for (const f of findings) {
    if (seen.has(f.id)) fail(`duplicate finding id ${f.id}`);
    seen.add(f.id);
  }
  findings.sort((a, b) => (a.id < b.id ? -1 : 1));
  return findings;
}

function renderSection(findings) {
  const lines = [
    SECTION,
    '',
    '<!-- Generated by scripts/discovery-to-roadmap.mjs from .spec-graph/DISCOVERY.md. Do not hand-edit. -->',
    '',
    '| Id | Finding | Source type | Impact | Proposed action | State |',
    '| --- | --- | --- | --- | --- | --- |',
  ];
  for (const f of findings) {
    const cells = [f.id, f.title, f.sourceType, f.impact, f.proposed, 'candidate'].map((c) => String(c).replace(/\|/g, '\\|'));
    lines.push(`| ${cells.join(' | ')} |`);
  }
  return lines.join('\n') + '\n';
}

function readCurrentSection() {
  if (!fs.existsSync(ROADMAP)) return null;
  const txt = fs.readFileSync(ROADMAP, 'utf8');
  const start = txt.indexOf(SECTION);
  if (start === -1) return null;
  const rest = txt.slice(start + SECTION.length);
  const nextHeading = rest.search(/^##\s/m);
  return nextHeading === -1 ? txt.slice(start) : txt.slice(start, start + SECTION.length + nextHeading);
}

function applySection(section) {
  let txt = fs.existsSync(ROADMAP) ? fs.readFileSync(ROADMAP, 'utf8') : '';
  const current = readCurrentSection();
  if (current === null) {
    txt = txt.replace(/\s*$/, '\n\n') + section;
  } else {
    const start = txt.indexOf(SECTION);
    const rest = txt.slice(start + SECTION.length);
    const nextHeading = rest.search(/^##\s/m);
    const end = nextHeading === -1 ? txt.length : start + SECTION.length + nextHeading;
    txt = txt.slice(0, start) + section + (nextHeading === -1 ? '' : txt.slice(end));
  }
  fs.writeFileSync(ROADMAP, txt);
}

const findings = parseDiscovery();
if (!findings) process.exit(0);

const mode = process.argv[2] || '--check';
const expected = renderSection(findings);
const current = readCurrentSection();

if (mode === '--apply') {
  applySection(expected);
  console.log(`DISCOVERY-APPLIED — ${findings.length} candidate(s) rendered into .spec-graph/ROADMAP.md`);
  process.exit(0);
}

if (mode === '--check') {
  if (current === null) {
    console.error(`DISCOVERY-DRIFT — "${SECTION}" section missing from .spec-graph/ROADMAP.md (run: node scripts/discovery-to-roadmap.mjs --apply)`);
    process.exit(1);
  }
  if (current.trim() !== expected.trim()) {
    console.error(`DISCOVERY-DRIFT — "${SECTION}" differs from the rendered discovery log (run: node scripts/discovery-to-roadmap.mjs --apply)`);
    process.exit(1);
  }
  console.log(`DISCOVERY-OK — ${findings.length} candidate(s) match .spec-graph/DISCOVERY.md`);
  process.exit(0);
}

console.error('usage: discovery-to-roadmap.mjs [--apply|--check]');
process.exit(2);
